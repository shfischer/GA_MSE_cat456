### ------------------------------------------------------------------------ ###
### OEM (observations) - length sampling ####
### ------------------------------------------------------------------------ ###
### generate sampled length frequency data from catch
### use Henning Winker's two-stage sampling from FLRef
### https://github.com/flr/FLRef/blob/fa570ee8042dbf590f8a30ae8421770651e72554/R/lensim.R#L556-L694
### developed during ICES WKdsDLSMethDev

oem_lfd_sampling <- function(stk, 
                             observations, 
                             deviances, 
                             args, 
                             tracking,
                             gears,
                             ### effective sample size(s)
                             ess_age = gears[[1]]$ess_age,
                             ess_len = gears[[1]]$ess_len,
                             ...) {
  
  FLCore::spread(args)
  
  ### pass on stock without error (not used)
  observations$stk <- stk
  stk0 <- window(stk, start = y0, end = dy, extend = FALSE)
  
  cn <- catch.n(stk[, ac(dys)])
  cn[cn <= 0] <- sqrt(.Machine$double.eps) ### avoid zeros
  len_sim <- lfd.sim(object = cn, 
                     gear = gears[[1]], 
                     ess_age = ess_age,
                     ess_len = ess_len,
                     scale = FALSE,
                     u_age = deviances$lfd$age,
                     u_len = deviances$lfd$len
  )
  
  ### store length observation in index object
  index(observations$idx$LFD)[, ac(dys)] <- len_sim
  
  idx0 <- window(observations$idx, end = dy)
  
  return(list(stk = stk0, idx = idx0, observations = observations, 
              tracking = tracking))
  
}

### ------------------------------------------------------------------------ ###
### EST (estimator) - use sampled length data and get catch curve slope ####
### ------------------------------------------------------------------------ ###
### takes the data generated by oem_len_sampling
### and applies a length-based catch curve
### fits a linear model to the descending limb of the catch curve
### and uses the slope as a proxy for total mortality

est_lfd_lcc <- function(stk, idx, args, tracking, Linf, ...) {
  
  #browser()
  FLCore::spread(args)
  
  ### get length data
  ### if several data years, combine (sum)
  len_data <- yearSums(index(idx$LFD)[, ac(dys)])
  
  ### apply lm to length catch curves
  idx_s <- lcc_fun(len_data = len_data, Linf = Linf)
  
  return(list(stk = stk, tracking = tracking, ind = FLQuants(s = idx_s)))
  
}

lcc_fun <- function(len_data, Linf) {
  idx_s <- apply(len_data, MARGIN = c(2:6), function(x) {
    #browser()
    tmp <- data.frame(length = as.numeric(names(x)),
                      N = x)
    ### keep only data at/above mode
    ### but remove last age/plusgroup when finding mode
    x_keep <- seq(which.max(x[-length(x)]), length(x))
    tmp <- tmp[x_keep, ]
    ### remove lengths above Linf
    tmp <- tmp[tmp$length < Linf, ]
    ### remove 0s
    tmp <- tmp[tmp$N > 0, ]
    ### format data for linear regression
    tmp$lrel <- -log(1-(tmp$length)/Linf)
    tmp$logN <- log(tmp$N)
    ### logN vs relative age (length converted to relative age)
    out <- try(lm(logN ~ lrel, data = tmp)$coefficients[[2]],
               silent = TRUE)
    if (is(out, "try-error") | is.na(out)) {
      return(0) ### return 0, i.e. no trend detected
    } else {
      return(-out) ### slope is negative -> return positive value
    }
    
  })
  return(idx_s)
}

### ------------------------------------------------------------------------ ###
### PHCR - lcc with sampled LFD ####
### ------------------------------------------------------------------------ ###
### parameterise HCR
phcr_lfd_lcc <- function(stk, args, tracking,
                         ind, ### indicator with catch curve slope
                         m, ### multiplier
                         s_target, ### target catch curve slope
                         catch_limit, ### absolute catch limit
                         ...) {
  
  FLCore::spread(args)
  
  ### structure for parameters
  hcrpars <- FLPar(NA, dimnames = list(
    params = c("Ay", "s", "s_target", "m", "catch_limit"),
    iter = seq(dim(stk)[6])), units = "")
  
  ### insert parameters
  hcrpars["s_target"] <- s_target
  hcrpars["s"] <- ind$s[, ac(dy)]
  hcrpars["m"] <- m
  hcrpars["catch_limit"] <- catch_limit
  ### previous catch/advice
  if (identical(ay, iy)) {
    ### first simulation year
    hcrpars["Ay"] <- tracking$data[tracking$year == ay & tracking$metric == "C.om"]
  } else {
    ### following years
    hcrpars["Ay"] <- tracking$data[tracking$year == (args$ay - 1) &
                                     tracking$metric == "hcr"]
  }
  
  return(list(hcrpars = hcrpars, tracking = tracking))
  
}

### ------------------------------------------------------------------------ ###
### HCR - lcc with sampled LFD ####
### ------------------------------------------------------------------------ ###
### apply HCR and calculate catch advice
hcr_lcc_lfd <- function(stk, hcrpars, args, tracking,
                        interval,
                        upper_constraint = 1.2, ### relative catch constraint
                        lower_constraint = 0.7,
                        ...) {
  
  FLCore::spread(args)
  
  ### check if new advice requested
  if (identical((ay - iy) %% interval, 0)) {
    
    ### calculate advice
    advice <- hcrpars["Ay", ] *
      (hcrpars["s_target", ]/hcrpars["s", ]) *
      hcrpars["m", ]
    
    ### apply relative catch constraint
    if (!is.infinite(upper_constraint) | lower_constraint != 0) {
      ### new/old advice ratio
      adv_ratio <- c(advice/hcrpars["Ay"])
      
      ### limit changes
      adv_ratio <- pmax(adv_ratio, lower_constraint)
      adv_ratio <- pmin(adv_ratio, upper_constraint)
      
      advice[] <- hcrpars["Ay"] * adv_ratio
    }
    
    ### apply absolute catch limit
    ### overwrite relative catch constraint
    ### catch can never exceed this value
    advice[] <- ifelse(c(advice > hcrpars["catch_limit"]),
                       c(hcrpars["catch_limit"]),
                       c(advice))
    
  } else {
    
    ### use last year's advice
    advice <- hcrpars["Ay", ]
    
    
  }
  
  ### create fwdControl object
  ctrl <- fwdControl(list(year = ay + management_lag,
                          quant = "catch",
                          value = c(advice)))

  
  return(list(ctrl = ctrl, tracking = tracking))
  
}


